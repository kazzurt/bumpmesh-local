// Copy pinned runtime dependencies into the app. npm is needed only to refresh them.
import { cp, mkdir, readFile, writeFile } from 'node:fs/promises';
import { fileURLToPath } from 'node:url';
import path from 'node:path';

const root = fileURLToPath(new URL('../', import.meta.url));
const vendor = path.join(root, 'vendor');
await mkdir(vendor, { recursive: true });
for (const name of ['three', 'fflate', 'meshstep']) {
  const src = path.join(root, 'node_modules', name);
  const pkg = JSON.parse(await readFile(path.join(src, 'package.json'), 'utf8'));
  const dest = path.join(vendor, name);
  await mkdir(dest, { recursive: true });
  if (name === 'three') {
    await cp(path.join(src, 'build'), path.join(dest, 'build'), { recursive: true });
    await cp(path.join(src, 'examples', 'jsm'), path.join(dest, 'examples', 'jsm'), { recursive: true });
  } else if (name === 'fflate') {
    await cp(path.join(src, 'esm'), path.join(dest, 'esm'), { recursive: true });
  } else {
    // meshStep's distribution has relative imports. Preserve its package structure.
    await cp(src, dest, { recursive: true });
  }
  await cp(path.join(src, 'LICENSE'), path.join(dest, 'LICENSE'));
  await cp(path.join(src, 'package.json'), path.join(dest, 'package.json'));
  console.log(`${name} ${pkg.version} copied locally`);
}
await writeFile(path.join(vendor, 'README.md'), `# Local runtime dependencies\n\nGenerated by \`npm run vendor\` from package-lock.json. Three.js 0.170.0, fflate 0.8.2 and meshStep 0.1.0 are pinned. Each package's license is retained. These files allow rendering, workers, STEP import and ZIP processing without a CDN connection.\n`);
